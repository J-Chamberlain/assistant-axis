#!/usr/bin/env python3
"""Evaluator-sensitivity comparison for Codex GPT-5.5 vs gpt-4.1-mini.

This is a methodology-validation script. It uses the canonical Lu-style
role-specific eval_prompt fields from data/roles/instructions/{role}.json.

Implementation note: Codex GPT-5.5 is not callable from Python in this local
environment. The Codex side of the comparison is therefore imported from the
existing audited Codex score JSONL files. The gpt-4.1-mini side is generated by
this script over the exact same response records and parsed with the same
integer parser used for all API judge outputs.
"""

