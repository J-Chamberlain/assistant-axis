def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit-api", type=int, default=None)
    parser.add_argument("--summarize-only", action="store_true")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    records = canonical_records()
    seen = existing_results()
    if not args.summarize_only:
        import_codex_scores(records, seen)
        score_gpt41mini(records, seen, limit=args.limit_api)
    summary = summarize()
    SUMMARY_JSON.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    if "editor" in summary["roles"]:
        write_confusion_csv(
            EDITOR_CONFUSION,
            summary["roles"]["editor"]["confusion_matrix_codex_rows_gpt41mini_cols"],
        )
    if "trickster" in summary["roles"]:
        write_confusion_csv(
            TRICKSTER_CONFUSION,
            summary["roles"]["trickster"]["confusion_matrix_codex_rows_gpt41mini_cols"],
        )
    write_report(summary)
    print(f"Wrote {RESULTS_JSONL.relative_to(ROOT)}")
    print(f"Wrote {SUMMARY_JSON.relative_to(ROOT)}")
    print(f"Wrote {REPORT_MD.relative_to(ROOT)}")
    print(f"Wrote {INTERPRETATION_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
